"""Track one frozen cohort with bounded parallelism, logs and resumable jobs.

No behavioral analysis is launched. Acquisition files and completed companions
are never replaced. Run from the repository root with PYTHONPATH=src.
"""

import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
from dataclasses import asdict
import fcntl
import json
import os
from pathlib import Path
import signal
import subprocess
import sys
import threading
import time

import cv2

from nvsl_offline.background import BackgroundConfig
from nvsl_offline.detection import DetectionConfig
from nvsl_offline.jumps import aggregate_comparisons
from nvsl_offline.pipeline import assert_sources, audit, load_run, producer, track
from nvsl_offline.recording import identity
from nvsl_offline.replay import Comparison


ROOT = Path(__file__).resolve().parents[1]


def read(path):
    return json.loads(Path(path).read_text())


def save(path, value):
    path = Path(path)
    temporary = path.with_suffix('.tmp')
    temporary.write_text(json.dumps(value, indent=2, allow_nan=False)+'\n')
    temporary.replace(path)


def verify_runtime(frozen):
    now = producer()
    for key in ('package_sha256', 'numpy_version', 'opencv_version'):
        if now[key] != frozen['producer'][key]:
            raise ValueError(f'Frozen runtime mismatch: {key}')
    DetectionConfig(**frozen['detector']).validate()
    BackgroundConfig(**frozen['background']).validate()


def verify_audit(path, job, frozen):
    rec, manifest, _, cal = load_run(path)
    if manifest['sources'] != job['sources'] or rec.shape != (job['slots'], job['frames']):
        raise ValueError('Audit differs from frozen recording identity or shape')
    if manifest['background_config'] != frozen['background'] or asdict(cal) != job['calibration']:
        raise ValueError('Audit background/calibration differs from frozen plan')
    expected_samples = min(job['frames'], frozen['audit']['samples'])
    if len(manifest['sample_indices']) != expected_samples:
        raise ValueError('Audit sample count differs from frozen plan')
    return manifest


def verify_companion(path, job, frozen, manifest):
    comparison = Comparison.load(path)
    meta = comparison.variant.raw['tracking_metadata']
    expected = dict(detector=frozen['detector'], background=frozen['background'],
                    calibration=job['calibration'], exclude_slots=[])
    if meta['configuration'] != expected or meta['source_recording'] != job['sources']:
        raise ValueError('Companion configuration/source differs from frozen plan')
    if meta['background_sha256'] != manifest['background_sha256']:
        raise ValueError('Companion belongs to a different background audit')
    if meta['producer']['package_sha256'] != frozen['producer']['package_sha256']:
        raise ValueError('Companion was generated by different tracker code')
    return identity(Path(path), content_hash=True)


def execute_job(directory):
    directory = Path(directory)
    job, frozen = read(directory/'input.json'), read(directory.parent/'freeze.json')
    progress_path = directory/'progress.json'
    progress = read(progress_path) if progress_path.exists() else dict(attempts=0)

    def update(**values):
        progress.update(values, updated=time.time())
        save(progress_path, progress)
        print(f"{Path(job['video']).name}: {progress.get('stage')}", flush=True)

    try:
        verify_runtime(frozen)
        assert_sources(job['sources'])
        if job.get('acquisition_note'):
            assert_sources({'note': job['acquisition_note']})
        was_complete = progress.get('stage') == 'complete'
        if was_complete:
            manifest = verify_audit(progress['audit'], job, frozen)
            current = verify_companion(progress['companion'], job, frozen, manifest)
            if current != progress['companion_identity']:
                raise ValueError('Completed companion changed since previous invocation')
            if identity(Path(progress['comparison']), content_hash=True) != progress['comparison_identity']:
                raise ValueError('Completed diagnostic summary changed')
            return
        attempt = int(progress.get('attempts', 0))+1
        work = directory/f'attempt-{attempt:03d}'
        work.mkdir()
        update(attempts=attempt, stage='checking', error=None)
        audit_path = Path(progress.get('audit', work/'audit'))
        if not (audit_path/'manifest.json').is_file():
            audit_path = work/'audit'
            update(stage='auditing', audit=str(audit_path))
            audit(job['video'], audit_path, **frozen['audit'],
                  config=BackgroundConfig(**frozen['background']))
        manifest = verify_audit(audit_path, job, frozen)
        verify_runtime(frozen)
        companion = Path(progress.get('companion', work/(Path(job['video']).stem+'.body-core.offline.trx')))
        if not companion.exists():
            companion = work/(Path(job['video']).stem+'.body-core.offline.trx')
            update(stage='tracking', companion=str(companion), audit=str(audit_path))
            track(audit_path, companion, config=DetectionConfig(**frozen['detector']))
        companion_identity = verify_companion(companion, job, frozen, manifest)
        if progress.get('companion_identity') and progress['companion_identity'] != companion_identity:
            raise ValueError('Previously published companion changed')
        comparison_dir = work/'comparison'
        update(stage='comparing', companion=str(companion), companion_identity=companion_identity,
               comparison=str(comparison_dir/'summary.json'))
        subprocess.run([sys.executable, str(ROOT/'scripts/compare_jump_trajectories.py'),
                        str(companion), '--output', str(comparison_dir)], check=True)
        verify_runtime(frozen)
        assert_sources(job['sources'])
        if job.get('acquisition_note'):
            assert_sources({'note': job['acquisition_note']})
        update(stage='complete', comparison_identity=identity(comparison_dir/'summary.json', content_hash=True))
    except Exception as exc:
        update(stage='failed', error=f'{type(exc).__name__}: {exc}')
        raise


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cohort', help='Frozen cohort manifest JSON')
    parser.add_argument('--output', help='New batch directory, or same directory with --resume')
    parser.add_argument('--workers', type=int, default=3)
    parser.add_argument('--resume', action='store_true')
    parser.add_argument('--dry-run', action='store_true', help='Validate local plan/runtime and list jobs; create no outputs')
    parser.add_argument('--execute-job', help=argparse.SUPPRESS)
    args = parser.parse_args()
    cv2.setNumThreads(1)
    if args.execute_job:
        execute_job(args.execute_job)
        return
    if not args.cohort or not args.output or not 1 <= args.workers <= 8:
        parser.error('--cohort, --output and workers in [1,8] are required')
    cohort_path = Path(args.cohort).resolve(strict=True)
    cohort = read(cohort_path)
    freeze_path = Path(cohort['freeze']).resolve(strict=True)
    frozen = read(freeze_path)
    verify_runtime(frozen)
    jobs = [j for j in cohort['jobs'] if j['disposition'] == 'ready_for_audit']
    held = [j for j in cohort['jobs'] if j['disposition'] == 'hold']
    if not jobs or len(jobs)+len(held) != len(cohort['jobs']):
        parser.error('No ready jobs or unknown disposition')
    print(f"{cohort['name']}: {len(jobs)} ready, {len(held)} held; workers={args.workers}", flush=True)
    out = Path(args.output).resolve()
    if args.dry_run:
        print('Dry run: no acquisition files decoded or output files created.')
        for job in jobs:
            print(f"{job['index']+1:02d}: {job['video']}")
        return
    if args.resume:
        if not out.is_dir():
            parser.error('--resume requires an existing batch directory')
    else:
        out.mkdir(parents=True, exist_ok=False)
    with (out/'.batch.lock').open('a') as batch_lock:
        try:
            fcntl.flock(batch_lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            raise SystemExit('Another process is already using this batch directory')
        run_batch(args, cohort_path, freeze_path, cohort, frozen, jobs, held, out)


def run_batch(args, cohort_path, freeze_path, cohort, frozen, jobs, held, out):
    provenance = dict(cohort=identity(cohort_path, content_hash=True),
                      freeze=identity(freeze_path, content_hash=True),
                      runner=identity(Path(__file__), content_hash=True),
                      diagnostics=identity(ROOT/'scripts/compare_jump_trajectories.py', content_hash=True))
    status_path = out/'status.json'
    if args.resume:
        state = read(status_path)
        if state['inputs'] != provenance:
            raise ValueError('Frozen inputs or runner changed; refusing to resume a different experiment')
        if read(out/'freeze.json') != frozen:
            raise ValueError('Batch configuration snapshot changed')
    else:
        save(out/'freeze.json', frozen)
        save(out/'cohort.json', cohort)
        state = dict(schema_version=1, cohort=cohort['name'], inputs=provenance,
                     producer=producer(), started=time.time(), held=held, jobs=[])
        for job in jobs:
            directory = out/f"{job['index']+1:02d}-{Path(job['video']).stem}"
            directory.mkdir()
            save(directory/'input.json', job)
            state['jobs'].append(dict(index=job['index'], video=job['video'], stage='waiting',
                                      directory=str(directory), warnings=job['warnings']))
    # Validate saved job inputs before starting any resumed work.
    if len(state['jobs']) != len(jobs):
        raise ValueError('Batch job list changed')
    for saved, expected in zip(state['jobs'], jobs):
        if read(Path(saved['directory'])/'input.json') != expected:
            raise ValueError('Saved job input differs from cohort manifest')
    state.update(workers=args.workers, complete=False, resumed=time.time(),
                 opencv_threads_per_worker=1, behavior_analysis_launched=False)
    state.pop('aggregate', None)
    lock, stopping = threading.Lock(), threading.Event()

    def update(job=None, **values):
        with lock:
            if job is not None:
                job.update(values)
            state['updated'] = time.time()
            save(status_path, state)

    def run(job):
        if stopping.is_set():
            return
        directory = Path(job['directory'])
        log = directory/'job.log'
        update(job, log=str(log))
        env = dict(os.environ, PYTHONPATH=str(ROOT/'src'), PYTHONUNBUFFERED='1',
                   OPENBLAS_NUM_THREADS='1', OMP_NUM_THREADS='1')
        with log.open('a') as stream:
            stream.write(f'\nBatch invocation {time.time()}\n'); stream.flush()
            process = subprocess.Popen([sys.executable, str(Path(__file__).resolve()),
                                        '--execute-job', str(directory)], cwd=ROOT, env=env,
                                       stdout=stream, stderr=subprocess.STDOUT, start_new_session=True)
            while process.poll() is None:
                if stopping.wait(1):
                    try:
                        os.killpg(process.pid, signal.SIGTERM)
                        process.wait(timeout=10)
                    except ProcessLookupError:
                        pass
                    except subprocess.TimeoutExpired:
                        os.killpg(process.pid, signal.SIGKILL)
                        process.wait()
                    update(job, stage='interrupted')
                    return
                progress_path = directory/'progress.json'
                if progress_path.exists():
                    progress = read(progress_path)
                    if progress.get('stage') != job.get('stage'):
                        update(job, **progress)
                        print(f"{Path(job['video']).name}: {job['stage']}", flush=True)
            progress_path = directory/'progress.json'
            progress = read(progress_path) if progress_path.exists() else {}
            if process.returncode or progress.get('stage') != 'complete':
                progress.update(stage='failed', error=progress.get('error') or f'Worker exit {process.returncode}; see {log}')
            update(job, **progress)
            print(f"{Path(job['video']).name}: {job['stage']}", flush=True)

    update()
    pool = ThreadPoolExecutor(max_workers=args.workers)
    futures = []
    try:
        for job in state['jobs']:
            futures.append(pool.submit(run, job))
        for future in as_completed(futures):
            future.result()
    except KeyboardInterrupt:
        stopping.set()
        for future in futures:
            future.cancel()
        print('Stopping workers; completed outputs will be retained for --resume.', flush=True)
    except Exception:
        stopping.set()
        for future in futures:
            future.cancel()
        raise
    finally:
        pool.shutdown(wait=True, cancel_futures=True)
    state['complete'] = all(j['stage'] == 'complete' for j in state['jobs'])
    if state['complete']:
        comparisons = [row for job in state['jobs'] for row in read(job['comparison'])['comparisons']]
        state['aggregate'] = aggregate_comparisons(comparisons)
    state['finished'] = time.time()
    update()
    if not state['complete']:
        raise SystemExit(f'Batch incomplete; inspect {status_path} and use --resume to retry.')
    print(f'Batch complete: {status_path}', flush=True)


if __name__ == '__main__':
    def terminate(signum, frame):
        if '--execute-job' in sys.argv:
            raise SystemExit(143)
        raise KeyboardInterrupt
    signal.signal(signal.SIGTERM, terminate)
    main()
